def build_transition_matrix():
    m = [[0] * K for _ in range(K)]
    for src in range(K):
        for j in range(DECAY_COUNT[src]):
            dst = DECAY[src][j]
            m[dst][src] += 1
    return m

def multiply_matrix(a, b):
    c = [[0] * K for _ in range(K)]
    for i in range(K):
        for k in range(K):
            if a[i][k] == 0: continue
            aik = a[i][k]
            for j in range(K):
                if b[k][j] == 0: continue
                c[i][j] = (c[i][j] + aik * b[k][j]) & MASK
    return c

def apply_matrix(m, v):
    out = [0] * K
    for i in range(K):
        acc = 0
        for j in range(K):
            if m[i][j] == 0 or v[j] == 0: continue
            acc += m[i][j] * v[j]
        out[i] = acc & MASK
    return out

def evolve_vector(v, steps):
    power = build_transition_matrix()
    e = steps
    while e > 0:
        if e & 1:
            v = apply_matrix(power, v)
        e >>= 1
        if e > 0:
            power = multiply_matrix(power, power)
    return v

